 cinema_id uuid REFERENCES cinema.cinemas(id) ON DELETE CASCADE,
 assigned_at timestamptz NOT NULL DEFAULT now(),
 assigned_by uuid REFERENCES cinema.users(id) ON DELETE SET NULL,
 revoked_at timestamptz,
 CHECK (revoked_at IS NULL OR revoked_at >= assigned_at)
);
-- One active global role assignment and one active cinema-specific assignment of a role.
