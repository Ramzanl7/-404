-- This function is an authorization predicate, not a substitute for secure API auth.
-- Caller ID must be obtained from a server-verified session/JWT, NEVER client-provided user_id.
CREATE OR REPLACE FUNCTION cinema.has_permission(
 p_user_id uuid, p_permission text, p_cinema_id uuid DEFAULT NULL
) RETURNS boolean
LANGUAGE sql STABLE SET search_path = cinema, pg_temp AS $$
 SELECT EXISTS (
  SELECT 1 FROM cinema.users u
  JOIN cinema.user_role_assignments a ON a.user_id=u.id
  JOIN cinema.roles r ON r.id=a.role_id
  JOIN cinema.role_permissions rp ON rp.role_id=r.id
  WHERE u.id=p_user_id AND u.is_active AND a.revoked_at IS NULL
    AND rp.permission_code=p_permission
    AND (r.scope='global' OR (p_cinema_id IS NOT NULL AND a.cinema_id=p_cinema_id))
 );
$$;

-- Track changes in active roles. Do not allow untrusted SQL users to modify this table.
CREATE TABLE cinema.role_assignment_events (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 assignment_id uuid NOT NULL,
 user_id uuid NOT NULL,
 role_id smallint NOT NULL,
 cinema_id uuid,
 action text NOT NULL CHECK (action IN ('granted','revoked')),
 occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 changed_by uuid
);
CREATE OR REPLACE FUNCTION cinema.audit_role_assignment() RETURNS trigger
LANGUAGE plpgsql SET search_path = cinema, pg_temp AS $$
BEGIN
 IF TG_OP='INSERT' THEN
  INSERT INTO cinema.role_assignment_events(assignment_id,user_id,role_id,cinema_id,action,changed_by)
  VALUES (NEW.id,NEW.user_id,NEW.role_id,NEW.cinema_id,'granted',NEW.assigned_by);
 ELSIF OLD.revoked_at IS NULL AND NEW.revoked_at IS NOT NULL THEN
  INSERT INTO cinema.role_assignment_events(assignment_id,user_id,role_id,cinema_id,action,changed_by)
  VALUES (NEW.id,NEW.user_id,NEW.role_id,NEW.cinema_id,'revoked',NEW.assigned_by);
 END IF;
 RETURN NULL;
END $$;
CREATE TRIGGER tr_audit_role_assignment AFTER INSERT OR UPDATE OF revoked_at
 ON cinema.user_role_assignments FOR EACH ROW EXECUTE FUNCTION cinema.audit_role_assignment();

