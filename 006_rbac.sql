 ON cinema.user_role_assignments(user_id,role_id,cinema_id)
 WHERE cinema_id IS NOT NULL AND revoked_at IS NULL;
CREATE INDEX user_role_lookup_idx ON cinema.user_role_assignments(user_id,cinema_id)
 WHERE revoked_at IS NULL;

CREATE OR REPLACE FUNCTION cinema.validate_role_assignment() RETURNS trigger
LANGUAGE plpgsql SET search_path = cinema, pg_temp AS $$
DECLARE expected_scope text;
BEGIN
 SELECT scope INTO expected_scope FROM cinema.roles WHERE id=NEW.role_id;
 IF expected_scope IS NULL THEN RAISE EXCEPTION 'Unknown role'; END IF;
 IF (expected_scope='global' AND NEW.cinema_id IS NOT NULL)
    OR (expected_scope='cinema' AND NEW.cinema_id IS NULL) THEN
   RAISE EXCEPTION 'Role must be assigned with appropriate scope: %', expected_scope;
 END IF;
 IF TG_OP='UPDATE' AND (NEW.user_id,NEW.role_id,NEW.cinema_id,NEW.assigned_at)
    IS DISTINCT FROM (OLD.user_id,OLD.role_id,OLD.cinema_id,OLD.assigned_at) THEN
    RAISE EXCEPTION 'Role assignment is immutable; revoke it and create a new one';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_validate_role_assignment BEFORE INSERT OR UPDATE
 ON cinema.user_role_assignments FOR EACH ROW EXECUTE FUNCTION cinema.validate_role_assignment();

